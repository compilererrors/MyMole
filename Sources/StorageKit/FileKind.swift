import Foundation

/// What a file is, for the "by kind" coloring and totals.
public enum FileKind: Int, CaseIterable, Sendable, Codable {
    case apps, developer, caches, media, documents, archives, system, other

    public var title: String {
        switch self {
        case .apps: "Apps"
        case .developer: "Developer"
        case .caches: "Caches & Logs"
        case .media: "Photos, Music & Video"
        case .documents: "Documents"
        case .archives: "Archives & Installers"
        case .system: "System & Libraries"
        case .other: "Other"
        }
    }

    public var symbol: String {
        switch self {
        case .apps: "app.dashed"
        case .developer: "hammer"
        case .caches: "archivebox"
        case .media: "photo.on.rectangle"
        case .documents: "doc.text"
        case .archives: "shippingbox"
        case .system: "gearshape.2"
        case .other: "questionmark.folder"
        }
    }
}

/// Bytes per kind, stored inline (no dictionary) since every folder has one.
public struct KindBytes: Sendable, Equatable {
    public private(set) var values = [Int64](repeating: 0, count: FileKind.allCases.count)

    public init() {}

    public subscript(kind: FileKind) -> Int64 {
        get { values[kind.rawValue] }
        set { values[kind.rawValue] = newValue }
    }

    mutating func add(_ other: KindBytes) {
        for i in values.indices { values[i] += other.values[i] }
    }

    mutating func subtract(_ other: KindBytes) {
        for i in values.indices { values[i] = max(0, values[i] - other.values[i]) }
    }

    public var total: Int64 { values.reduce(0, +) }
}

/// A folder that tools recreate on demand, with why it's safe to remove.
public struct Rebuildable: Sendable, Hashable {
    public let label: String
    public let reason: String
}

/// MyMole's own rules for naming what's on disk. Folder rules set the kind
/// of everything beneath them (all of `node_modules` is developer data, all
/// of an `.app` is the app); otherwise a file's extension decides.
public enum Classifier {
    static let extensionKinds: [String: FileKind] = {
        var m: [String: FileKind] = [:]
        func put(_ kind: FileKind, _ exts: String) {
            for e in exts.split(separator: " ") { m[String(e)] = kind }
        }
        put(.media, "jpg jpeg png heic heif gif tiff tif raw cr2 cr3 nef arw dng webp bmp svg psd mov mp4 m4v avi mkv webm mp3 m4a aac wav aiff flac alac ogg opus caf logicx band")
        put(.documents, "pdf doc docx pages key keynote numbers xls xlsx ppt pptx txt rtf md csv json xml epub odt ods odp")
        put(.archives, "zip dmg pkg mpkg iso tar gz tgz bz2 xz 7z rar xip ipa apk")
        put(.developer, "swift m h c cc cpp hpp rs go py js ts tsx jsx java kt rb php cs o a dylib so class jar wasm map dSYM xcarchive")
        put(.system, "plist db sqlite sqlite3 sqlite-wal sqlite-shm framework bundle kext")
        put(.caches, "log cache tmp")
        return m
    }()

    /// Folder names whose whole subtree belongs to one kind.
    static let folderKinds: [String: FileKind] = [
        "node_modules": .developer, "DerivedData": .developer, ".gradle": .developer, ".cargo": .developer,
        ".rustup": .developer, ".npm": .developer, ".pnpm-store": .developer, ".m2": .developer,
        "Pods": .developer, ".venv": .developer, "venv": .developer, "__pycache__": .developer,
        "CoreSimulator": .developer, "Xcode": .developer, ".build": .developer, "target": .developer,
        "Caches": .caches, "Logs": .caches, ".cache": .caches, "tmp": .caches,
        ".Trash": .other,
    ]

    /// Regenerated by the tool that made them. Mirrors what developers
    /// actually delete by hand when the disk fills up.
    static let rebuildableFolders: [String: Rebuildable] = [
        "node_modules": Rebuildable(label: "npm packages", reason: "Reinstalled by npm/yarn/pnpm install."),
        "DerivedData": Rebuildable(label: "Xcode build data", reason: "Xcode rebuilds it on the next build."),
        ".gradle": Rebuildable(label: "Gradle cache", reason: "Gradle downloads and rebuilds it."),
        "Pods": Rebuildable(label: "CocoaPods", reason: "Restored by pod install."),
        "__pycache__": Rebuildable(label: "Python bytecode", reason: "Python recompiles it on import."),
        ".venv": Rebuildable(label: "Python environment", reason: "Recreate with your requirements file."),
        ".pnpm-store": Rebuildable(label: "pnpm store", reason: "pnpm refetches packages."),
        ".npm": Rebuildable(label: "npm cache", reason: "npm refetches packages."),
        "Caches": Rebuildable(label: "Caches", reason: "Apps rebuild caches as needed."),
        ".cache": Rebuildable(label: "Tool cache", reason: "Tools rebuild it as needed."),
    ]

    /// Names that are only rebuildable next to a project file, so a folder
    /// someone happens to call "build" isn't flagged on its name alone.
    static let projectOutputs: [String: (marker: [String], rule: Rebuildable)] = [
        "target": (["Cargo.toml", "pom.xml"], Rebuildable(label: "Build output", reason: "Rebuilt by cargo/maven.")),
        ".build": (["Package.swift"], Rebuildable(label: "SwiftPM build", reason: "Rebuilt by swift build.")),
        "build": (["package.json", "build.gradle", "CMakeLists.txt", "build.gradle.kts"], Rebuildable(label: "Build output", reason: "Rebuilt by the project's build.")),
        "dist": (["package.json", "setup.py", "pyproject.toml"], Rebuildable(label: "Build output", reason: "Rebuilt by the project's build.")),
    ]

    public static func kind(ofFile name: String) -> FileKind {
        guard let dot = name.lastIndex(of: "."), dot != name.startIndex else { return .other }
        return extensionKinds[name[name.index(after: dot)...].lowercased()] ?? .other
    }

    /// The kind a folder imposes on everything inside it, if any.
    public static func kind(ofFolder name: String) -> FileKind? {
        if name.hasSuffix(".app") { return .apps }
        if name.hasSuffix(".xcarchive") || name.hasSuffix(".dSYM") { return .developer }
        if name.hasSuffix(".photoslibrary") || name.hasSuffix(".fcpbundle") { return .media }
        return folderKinds[name]
    }

    /// `siblings` are the other entries in the folder's parent, used to
    /// confirm build-output folders sit next to their project file.
    public static func rebuildable(folder name: String, siblings: Set<String>) -> Rebuildable? {
        if let r = rebuildableFolders[name] { return r }
        if let p = projectOutputs[name], p.marker.contains(where: siblings.contains) { return p.rule }
        return nil
    }
}
